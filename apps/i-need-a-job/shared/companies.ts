/** Companies per request. Title searches make several upstream calls per company, so they get smaller batches. */
const BOARD_BATCH = 20;
const SEARCH_BATCH = 8;

function chunk<T>(items: readonly T[], size: number): T[][] {
  const out: T[][] = [];
  for (let i = 0; i < items.length; i += size) out.push(items.slice(i, i + size));
  return out;
}

/**
 * A search requests companies in fixed batches (one function call each) rather
 * than one by one, to keep function calls and CDN requests down. Batch numbers
 * are positions in this list, so they change when COMPANIES does; each deploy
 * clears the CDN cache, which keeps them consistent.
 */
export const BATCHES: readonly (readonly Company[])[] = [
  ...chunk(
    COMPANIES.filter((co) => !SEARCH_SOURCES.has(co.source)),
    BOARD_BATCH,
  ),
  ...chunk(
    COMPANIES.filter((co) => SEARCH_SOURCES.has(co.source)),
    SEARCH_BATCH,
  ),
];

const BY_NAME = new Map(COMPANIES.map((co) => [co.name, co]));

export function industryOf(companyName: string): Industry | undefined {
  return BY_NAME.get(companyName)?.industry;
}
