// Companies whose job boards we query. Each slug was checked against the live
// API, and that it belongs to this company. Add a company by finding its board URL
// and confirming the API returns its postings:
//   greenhouse       boards.greenhouse.io/<slug>
//   lever            jobs.lever.co/<slug>
//   ashby            jobs.ashbyhq.com/<slug>
//   smartrecruiters  jobs.smartrecruiters.com/<CompanyId>
//   bamboohr         <slug>.bamboohr.com/careers
//   breezy           <slug>.breezy.hr
//   rippling         ats.rippling.com/<slug>/jobs
//   gem              jobs.gem.com/<slug>
//   workday          <tenant>.wd<N>.myworkdayjobs.com/<site>  → slug "<tenant>/wd<N>/<site>"
//   oracle           <host>/hcmUI/CandidateExperience/en/sites/<site>  → slug "<host>/<site>"
// Workday and Oracle are the JSON endpoints behind employers' own career sites,
// not documented APIs, so they can change without notice.

export type JobSource =
  | "greenhouse"
  | "lever"
  | "ashby"
  | "smartrecruiters"
  | "bamboohr"
  | "breezy"
  | "rippling"
  | "gem"
  | "workday"
  | "oracle";

