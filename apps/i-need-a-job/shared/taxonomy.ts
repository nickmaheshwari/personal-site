// Job families used to turn a resume into related job titles.
//
// - titles: titles in the family, as they appear on postings. Aliases are extra
//   phrasings that count as the resume "mentioning" that title.
// - keywords: skills/terms that signal the family. Each distinct hit adds 1 to
//   the family's score.
// - adjacent: families someone in this family could plausibly move into. Their
//   titles are offered as stretch suggestions.

export interface FamilyTitle {
  title: string;
  aliases?: readonly string[];
  /** The bare title is too generic to detect in a resume ("server", "editor"); only aliases count as mentions. */
  aliasesOnly?: boolean;
}

export interface JobFamily {
  id: string;
  titles: readonly FamilyTitle[];
  keywords: readonly string[];
  adjacent: readonly string[];
}

